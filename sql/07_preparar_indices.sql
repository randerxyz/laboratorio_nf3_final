DROP TABLE IF EXISTS PEDIDO_MASSA;
CREATE TABLE PEDIDO_MASSA(
 id INT PRIMARY KEY,cid INT NOT NULL,status VARCHAR(12) NOT NULL,
 criado_em DATE NOT NULL,observacao VARCHAR(100) NOT NULL
) ENGINE=InnoDB;
INSERT INTO PEDIDO_MASSA
WITH dig AS (SELECT 0 n UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
 UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9),
 numeros AS (SELECT a.n+10*b.n+100*c.n+1000*d.n+10000*e.n+1 n
 FROM dig a CROSS JOIN dig b CROSS JOIN dig c CROSS JOIN dig d CROSS JOIN dig e)
SELECT n,MOD(n,1000)+1,IF(MOD(n,3)=0,'CONCLUIDO','PENDENTE'),
 DATE_ADD('2026-01-01',INTERVAL MOD(n,300) DAY),RPAD('massa',80,'x') FROM numeros;

USE loja_cerrado;
SELECT VERSION(),@@version_comment,@@default_storage_engine,@@transaction_isolation,@@autocommit;
SHOW TABLES;
SHOW CREATE TABLE ITEM;
SHOW CREATE TABLE ENDERECO_ENTREGA;
SELECT TABLE_NAME,ENGINE,TABLE_COLLATION FROM information_schema.TABLES
 WHERE TABLE_SCHEMA='loja_cerrado' ORDER BY TABLE_NAME;
SELECT TABLE_NAME,CONSTRAINT_NAME,CONSTRAINT_TYPE FROM information_schema.TABLE_CONSTRAINTS
 WHERE TABLE_SCHEMA='loja_cerrado' ORDER BY TABLE_NAME,CONSTRAINT_NAME;
SELECT 'CLIENTE' tabela,COUNT(*) n FROM CLIENTE
UNION ALL SELECT 'PEDIDO',COUNT(*) FROM PEDIDO
UNION ALL SELECT 'PRODUTO',COUNT(*) FROM PRODUTO
UNION ALL SELECT 'ITEM',COUNT(*) FROM ITEM
UNION ALL SELECT 'CLIENTE_PF',COUNT(*) FROM CLIENTE_PF
UNION ALL SELECT 'CLIENTE_PJ',COUNT(*) FROM CLIENTE_PJ
UNION ALL SELECT 'ENDERECO_ENTREGA',COUNT(*) FROM ENDERECO_ENTREGA;
-- Totalidade e disjunção são verificadas por consulta, não impostas pelas FKs:
SELECT c.cid FROM CLIENTE c
 LEFT JOIN CLIENTE_PF f ON f.cid=c.cid LEFT JOIN CLIENTE_PJ j ON j.cid=c.cid
 WHERE (f.cid IS NULL AND j.cid IS NULL) OR (f.cid IS NOT NULL AND j.cid IS NOT NULL);

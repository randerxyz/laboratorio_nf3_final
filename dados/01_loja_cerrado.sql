DROP DATABASE IF EXISTS loja_cerrado;
CREATE DATABASE loja_cerrado CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE loja_cerrado;
CREATE TABLE CLIENTE (
 cid INT NOT NULL PRIMARY KEY, nome VARCHAR(100) NOT NULL, cidade VARCHAR(100) NOT NULL
) ENGINE=InnoDB;
CREATE TABLE PEDIDO (
 pid INT NOT NULL PRIMARY KEY, cid INT NOT NULL, status VARCHAR(12) NOT NULL,
 CONSTRAINT fk_pedido_cliente FOREIGN KEY (cid) REFERENCES CLIENTE(cid) ON UPDATE CASCADE ON DELETE RESTRICT,
 CONSTRAINT chk_pedido_status CHECK (status IN ('CONCLUIDO','PENDENTE','CANCELADO'))
) ENGINE=InnoDB;
CREATE TABLE PRODUTO (
 rid INT NOT NULL PRIMARY KEY, descricao VARCHAR(100) NOT NULL, categoria VARCHAR(100) NOT NULL
) ENGINE=InnoDB;
CREATE TABLE ITEM (
 pid INT NOT NULL, rid INT NOT NULL, qtd INT NOT NULL, preco DECIMAL(10,2) NOT NULL,
 PRIMARY KEY(pid,rid),
 CONSTRAINT fk_item_pedido FOREIGN KEY(pid) REFERENCES PEDIDO(pid) ON UPDATE CASCADE ON DELETE RESTRICT,
 CONSTRAINT fk_item_produto FOREIGN KEY(rid) REFERENCES PRODUTO(rid) ON UPDATE CASCADE ON DELETE RESTRICT,
 CONSTRAINT chk_item_qtd CHECK(qtd>0), CONSTRAINT chk_item_preco CHECK(preco>=0)
) ENGINE=InnoDB;
CREATE TABLE CLIENTE_PF (
 cid INT NOT NULL PRIMARY KEY, cpf CHAR(11) NOT NULL,
 UNIQUE KEY uq_cliente_pf_cpf(cpf),
 CONSTRAINT fk_pf_cliente FOREIGN KEY(cid) REFERENCES CLIENTE(cid) ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;
CREATE TABLE CLIENTE_PJ (
 cid INT NOT NULL PRIMARY KEY, cnpj CHAR(14) NOT NULL, contato VARCHAR(100) NOT NULL,
 UNIQUE KEY uq_cliente_pj_cnpj(cnpj),
 CONSTRAINT fk_pj_cliente FOREIGN KEY(cid) REFERENCES CLIENTE(cid) ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;
CREATE TABLE ENDERECO_ENTREGA (
 cid INT NOT NULL, seq INT NOT NULL, logradouro VARCHAR(150) NOT NULL,
 PRIMARY KEY(cid,seq),
 CONSTRAINT fk_endereco_cliente FOREIGN KEY(cid) REFERENCES CLIENTE(cid) ON UPDATE CASCADE ON DELETE RESTRICT,
 CONSTRAINT chk_endereco_seq CHECK(seq>0)
) ENGINE=InnoDB;
